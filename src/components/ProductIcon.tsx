import type { Product } from "@/lib/products";

/**
 * The square logo tile on a product card and in the page header.
 *
 * Inline SVG rather than an icon font or image: these appear dozens of times
 * on the catalogue and must not cost a request each, or flash in late.
 */
export default function ProductIcon({ icon, size = 38 }: { icon: Product["icon"]; size?: number }) {
  const s = Math.round(size * 0.56);
  return (
    <span className="pico" data-icon={icon} style={{ width: size, height: size }}>
      {icon === "whatsapp" && <Whatsapp size={s} />}
      {icon === "telegram" && <Telegram size={s} />}
      {icon === "phone" && <Phone size={s} />}
      {icon === "both" && (
        <span className="pico-pair">
          <Whatsapp size={Math.round(s * 0.74)} />
          <Telegram size={Math.round(s * 0.74)} />
        </span>
      )}
    </span>
  );
}

